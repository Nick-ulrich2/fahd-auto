/**
 * Catalogue motos et scooters Fahd Auto.
 *
 * Même principe que cars.ts : un bloc `moto({...})` par véhicule, photos dans `public/cars/<slug>/`
 * et déclarées dans `photos.json`. Les données techniques sont celles du constructeur pour la version indiquée.
 */
import photosJson from "./photos.json";
import type { Car, Photo } from "./types";

const PHOTOS = photosJson as unknown as Record<string, Photo[]>;

type Input = Omit<
  Car,
  | "kind" | "ref" | "photos" | "keys" | "carPass" | "coc" | "accidentFree" | "serviceHistory" | "warrantyMonths"
  | "location" | "doors" | "euroNorm" | "towing" | "airbags" | "colorInt" | "upholstery" | "wheelsInch" | "seats"
  | "colorExtName" | "performance"
> &
  Partial<Pick<Car, "keys" | "carPass" | "coc" | "accidentFree" | "serviceHistory" | "warrantyMonths" | "location" | "euroNorm" | "seats">> & {
    topSpeed: number;
    sold?: boolean;
  };

let n = 2000;
function moto({ topSpeed, ...c }: Input): Car & { sold?: boolean } {
  n += 1;
  return {
    keys: 2,
    carPass: false,
    coc: true,
    accidentFree: true,
    serviceHistory: true,
    warrantyMonths: 0,
    location: "brussels",
    euroNorm: c.year >= 2021 ? "Euro 5" : "Euro 4",
    seats: 2,
    doors: 0,
    towing: 0,
    airbags: 0,
    colorInt: "black",
    colorExtName: "",
    upholstery: "fabric",
    wheelsInch: 17,
    performance: { zeroTo100: 0, topSpeed },
    ...c,
    kind: "moto",
    ref: `FM-${n}`,
    photos: PHOTOS[c.slug] ?? [],
  };
}

/** Taux fixe FCFA (XAF) / euro. */
export const XAF_PER_EUR = 655.957;

/** Prix saisi en FCFA : renseigne aussi l'équivalent en euros. */
function xaf(amount: number) {
  return { priceXaf: amount, priceFrom: Math.round(amount / XAF_PER_EUR) };
}

